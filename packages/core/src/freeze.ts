/**
 * Recursively freeze a data literal so content tables cannot be changed at
 * runtime by accident (the prototype used to attach fields to its tables).
 */
export function deepFreeze<T>(value: T): T {
  if (value !== null && typeof value === 'object' && !Object.isFrozen(value)) {
    Object.freeze(value);
    for (const v of Object.values(value as Record<string, unknown>)) deepFreeze(v);
  }
  return value;
}
